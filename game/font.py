_glyphs = {}  # символ -> (u, v, ширина)


def init():
    """Запекает глифы в банк изображений FONT_BANK."""
    img = pyxel.images[FONT_BANK]
    per_row = img.width // CELL
    for i, (ch, rows) in enumerate(_RAW.items()):
        u = (i % per_row) * CELL
        v = (i // per_row) * CELL
        data = ["".join("7" if c == "#" else "0" for c in row) for row in rows]
        img.set(u, v, data)
        _glyphs[ch] = (u, v, len(rows[0]))


def _glyph(ch):
    ch = ch.upper()
    ch = _ALIASES.get(ch, ch)
    return _glyphs.get(ch) or _glyphs["?"]


def text_width(s):
    w = 0
    for ch in s:
        w += _glyph(ch)[2] + SPACING
    return max(0, w - SPACING)


def text(x, y, s, col, shadow=None):
    """Рисует строку. shadow — цвет тени (смещение +1,+1) или None."""
    if shadow is not None:
        _draw(x + 1, y + 1, s, shadow)
    _draw(x, y, s, col)


def _draw(x, y, s, col):
    pyxel.pal(7, col)
    cx = x
    for ch in s:
        if ch == "\n":
            cx = x
            y += LINE_H
            continue
        u, v, w = _glyph(ch)
        if ch != " ":
            pyxel.blt(cx, y, FONT_BANK, u, v, w, GLYPH_H, 0)
        cx += w + SPACING
    pyxel.pal()


def text_big(cx, y, s, col, scale=2, shadow=None):
    """Крупный текст, выровненный по центру cx."""
    total = text_width(s) * scale
    for offset, c in (((scale, scale), shadow), ((0, 0), col)):
        if c is None:
            continue
        pyxel.pal(7, c)
        x = cx - total / 2 + offset[0]
        for ch in s:
            u, v, w = _glyph(ch)
            if ch != " ":
                pyxel.blt(x + (w * scale - w) / 2, y + offset[1] + (GLYPH_H * scale - GLYPH_H) / 2,
                          FONT_BANK, u, v, w, GLYPH_H, 0, scale=scale)
            x += (w + SPACING) * scale
        pyxel.pal()


def text_center(cx, y, s, col, shadow=None):
    text(cx - text_width(s) // 2, y, s, col, shadow)


def wrap(s, max_w):
    """Разбивает строку на строки шириной не более max_w пикселей."""
    lines = []
    for para in s.split("\n"):
        cur = ""
        for word in para.split(" "):
            cand = word if not cur else cur + " " + word
            if text_width(cand) <= max_w or not cur:
                cur = cand
            else:
                lines.append(cur)
                cur = word
        lines.append(cur)
    return lines
